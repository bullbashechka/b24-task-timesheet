def runs(par, text):
    """Text with `code` spans in Consolas and **bold** spans."""
    parts = []
    buf, mode, i = "", None, 0
    while i < len(text):
        if text.startswith("**", i):
            parts.append((buf, mode)); buf = ""; mode = None if mode == "b" else "b"; i += 2; continue
        if text[i] == "`":
            parts.append((buf, mode)); buf = ""; mode = None if mode == "c" else "c"; i += 1; continue
        buf += text[i]; i += 1
    parts.append((buf, mode))
    for t, m in parts:
        if not t:
            continue
        r = par.add_run(t)
        if m == "b":
            r.bold = True
        if m == "c":
            # plain text, like the reference: Consolas is missing on a Mac, and colour would read as a link
            pass
    return par


def p(text, style=None):
    return runs(doc.add_paragraph(style=style), text)


def h1(t):
    doc.add_heading(t, level=1)


def h2(t):
    doc.add_heading(t, level=2)


def bullets(items, style="List Bullet"):
    for it in items:
        p(it, style)


def numbered(items):
    # plain "1." prefixes keep each list starting at 1 without numbering restarts
    for n, it in enumerate(items, 1):
        par = doc.add_paragraph(style="Normal")
        par.paragraph_format.left_indent = Cm(0.75)
        par.paragraph_format.first_line_indent = Cm(-0.6)
        par.paragraph_format.space_after = Pt(3)
        r = par.add_run(f"{n}.  ")
        r.bold = True
        r.font.color.rgb = BLUE
        runs(par, it)


def cell_props(cell, width, fill=None):
    tcpr = cell._element.get_or_add_tcPr()
    borders = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        e = OxmlElement(f"w:{side}")
        e.set(qn("w:val"), "single"); e.set(qn("w:sz"), "4"); e.set(qn("w:color"), "C9D1DA")
        borders.append(e)
    tcpr.append(borders)
    if fill:
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear"); shd.set(qn("w:color"), "auto"); shd.set(qn("w:fill"), fill)
        tcpr.append(shd)
    mar = OxmlElement("w:tcMar")
    for side, w in (("top", 60), ("left", 100), ("bottom", 60), ("right", 100)):
        e = OxmlElement(f"w:{side}")
        e.set(qn("w:w"), str(w)); e.set(qn("w:type"), "dxa")
        mar.append(e)
    tcpr.append(mar)
    cell.width = width


def table(header, rows, widths_cm):
    t = doc.add_table(rows=0, cols=len(header))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    widths = [Cm(w) for w in widths_cm]
    for ri, row in enumerate([header] + rows):
        cells = t.add_row().cells
        for ci, txt in enumerate(row):
            c = cells[ci]
            cell_props(c, widths[ci], "EAF2FB" if ri == 0 else None)
            par = c.paragraphs[0]
            par.paragraph_format.space_after = Pt(0)
            par.paragraph_format.line_spacing = 1.1
            runs(par, txt)
            for r in par.runs:
                r.font.size = Pt(9.5)
                if ri == 0:
                    r.bold = True
        if ri == 0:
            trpr = t.rows[0]._tr.get_or_add_trPr()
            th = OxmlElement("w:tblHeader")
            trpr.append(th)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


def picture(path, caption):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_after = Pt(2)
    par.add_run().add_picture(path, width=Cm(17.0))
    cap = doc.add_paragraph()
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = cap.add_run(caption)
    r.italic = True
    r.font.size = Pt(9)
    r.font.color.rgb = GRAYTXT


